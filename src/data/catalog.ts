function makeStyles(
  prefix: string,
  psBase: string,
  specs: Array<[string, number, boolean, number]>,
  defaultActive: boolean,
): FontStyleVariant[] {
  return specs.map(([name, weight, italic, fileSizeKb]) => ({
    id: `${prefix}-${weight}${italic ? 'i' : ''}`,
    name,
    weight,
    italic,
    postScriptName: `${psBase}-${name.replace(/\s+/g, '')}`,
    activated: defaultActive,
    fileSizeKb,
  }));
}

